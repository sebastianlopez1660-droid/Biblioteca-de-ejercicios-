// Grupos musculares y anclajes de etiquetas para tren superior y core
import { GROUPS, ANCHORS } from './exercises.js';
const both = (f) => [f(1), f(-1)];
const arm = (seg, p, n) => both((s) => ({ seg: seg + (s > 0 ? '_L' : '_R'), p: [s * p[0], p[1], p[2]], n: [s * n[0], n[1], n[2]] }));
const chest = (p, n, bone = 'chest') => both((s) => ({ bone, p: [s * p[0], p[1], p[2]], n: [s * n[0], n[1], n[2]] }));
const def = (name, muscles, anchors) => { GROUPS[name] = muscles; ANCHORS[name] = anchors; };
